function pn_seq = lfsr_framesync(Nbits)
%{
LFSR_FRAMESYNC  Generate a deterministic PN (m-sequence-like) bit sequence for synchronization/training.

pn_seq = LFSR_FRAMESYNC(Nbits) returns a length-Nbits column vector of binary values (0/1)
generated by an order-11 linear feedback shift register (LFSR) with feedback polynomial
x^11 + x^2 + 1. The register is initialized with a non-zero state (all ones) and, for each step,
outputs the oldest register bit and updates the state using the XOR of tap positions 11 and 2.

Input:
  - Nbits : number of PN bits to generate (non-positive → returns empty)

Output:
  - pn_seq : [Nbits x 1] binary PN sequence (0/1)
%}

    n = 11;

    % Initial non-zero state (any non-zero works for an m-sequence)
    state = ones(n,1);  

    pn_seq = zeros(Nbits,1);

    for k = 1:Nbits
        % Output bit – choose one position and keep it consistent
        % Here we output the oldest bit s11 (state(end))
        pn_seq(k) = state(end);

        % Compute feedback bit (mod-2 sum of taps 11 and 2)
        feedback = xor(state(end), state(2));

        % Shift register: insert new bit at the "front"
        state = [feedback; state(1:end-1)];
    end
end
